#!/usr/bin/env node
// Bundles the Ask assistant's server into ONE file, worker/dist/worker.js, with the site's
// knowledge inside it. One file means it can be deployed with `wrangler deploy` or pasted
// into the Cloudflare dashboard. The knowledge is rebuilt from data/ and dist/ every time,
// so the assistant can never know more — or older — facts than the site it ships with.
// Run after `npm run build:site`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildKnowledge } from './knowledge.js';
import { buildIndex } from './core.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const strip = src => src.replace(/^import .*$/gm, '').replace(/^export /gm, '');

if (!fs.existsSync(path.join(ROOT, 'dist/about/index.html'))) {
  console.error('Build the site first: npm run build:site');
  process.exit(1);
}
const knowledge = buildKnowledge(ROOT);
// Pre-built search index: keeps each question inside Cloudflare's free-plan 10 ms CPU limit.
knowledge.index = buildIndex(knowledge.chunks);
const out = `// Generated by assistant/build-worker.js — do not edit. ${knowledge.count} knowledge chunks.
${strip(read('assistant/core.js'))}
${strip(read('worker/src/handler.js'))}
const KNOWLEDGE = ${JSON.stringify(knowledge)};
const ALLOW = makeLimiter();
export default {
  fetch(request, env) {
    return handle(request, env, { knowledge: KNOWLEDGE, fetch: (u, i) => fetch(u, i), now: () => Date.now(), allow: ALLOW });
  }
};
`;
fs.mkdirSync(path.join(ROOT, 'worker/dist'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'worker/dist/worker.js'), out);
fs.writeFileSync(path.join(ROOT, 'worker/dist/knowledge.json'), JSON.stringify({ ...knowledge, index: undefined }, null, 1));
console.log(`built worker/dist/worker.js  ${(out.length / 1024).toFixed(0)} KB, ${knowledge.count} chunks`);
